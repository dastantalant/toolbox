package com.trading.roulette.api.enums;

public enum GenerateType {

    /**
     * <strong>Случайная генерация (ГСЧ).</strong>
     * <p>Стандартный режим. Числа выпадают с равномерной вероятностью.
     * Используйте это для оценки реального ROI стратегии.</p>
     */
    RANDOM,

    /**
     * <strong>Ротация по номерам (0, 1, 2, ... 36, 0, 1...).</strong>
     * <p>Детерминированный режим. Полезен для проверки покрытия стола
     * и отладки логики выплат. Исключает фактор случайности.</p>
     */
    ROTATION_NUMBER,

    /**
     * <strong>Ротация по колесу (0, 32, 15, 19...).</strong>
     * <p>Эмулирует движение шарика строго по ячейкам физического колеса.
     * Полезен для проверки стратегий типа {@code NeighborStrategy} в идеальных условиях.</p>
     */
    ROTATION_WHEEL,

    /**
     * <strong>Только Красные (Случайные).</strong>
     * <p>Генерирует бесконечную серию красных.
     * Убийственно для стратегий, ставящих на Черное с прогрессией.</p>
     */
    RANDOM_RED_ONLY,

    /**
     * <strong>Только Черные (Случайные).</strong>
     * <p>Аналогично красным, но для черных.</p>
     */
    RANDOM_BLACK_ONLY,

    /**
     * <strong>Все кроме Единицы.</strong>
     * <p>Генерирует любые числа, кроме {@code SPOT_01}.
     * Создает искусственный "Гэп" (Gap) для числа 1.
     * Используется для тестирования {@code GapAnalysisStrategy} и проверки
     * условий выхода (Stop Loss), если число так и не выпадает.</p>
     */
    RANDOM_EXCEPT_ONE
}
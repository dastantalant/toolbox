package com.trading.roulette.api.annotation;

public enum Tag {
    /** Не определено */
    UNKOWN,

    /** Управляющие стратегии (портфельные менеджеры) */
    MANAGER,

    /** Стратегии на изменении размера ставки (Мартингейл, Д'Аламбер, Пароли) */
    PROGRESSIVE,

    /** Предиктивные стратегии (Марков, Байес, Счет) */
    PREDICTIVE,

    /** Стратегии, основанные на физике колеса (Соседи, Сектора, Почерк дилера) */
    PHYSICAL,

    /** Поиск визуальных или числовых паттернов (Серии, Повторы) */
    PATTERN,

    /** Статистические отклонения (Z-Score, Горячие/Холодные, Энтропия) */
    STATISTICAL,

    /** Искусственный интеллект и обучение (Q-Learning, RL) */
    AI,

    /** Стратегии покрытия поля (Романовский, 98%, 66%) */
    COVERAGE,

    /** Гибридные и адаптивные стратегии */
    HYBRID,

    /** Специальные/Инсайдерские/Тестовые */
    SPECIAL
}